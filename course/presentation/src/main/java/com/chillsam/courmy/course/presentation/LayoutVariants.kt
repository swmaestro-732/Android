package com.chillsam.courmy.course.presentation

/**
 * 화면 배치 A/B 스위치 모음.
 *
 * 새 배치를 넣되 예전 배치도 남겨 두고 오갈 수 있게 하려고 둔 곳이다. 값을 바꾸고 다시 빌드하면
 * 해당 화면이 통째로 예전 모습으로 돌아간다. 사용자가 앱에서 고르는 설정이 아니라 **개발 중 비교용**이라
 * 런타임 토글이나 설정 화면을 만들지 않았다.
 *
 * 배치가 한쪽으로 확정되면 그 스위치와 반대쪽 컴포저블을 함께 지운다. 이 파일이 비면 파일도 지운다.
 * [wiki-needed]
 */
object LayoutVariants {
    /**
     * 코스 상세에서 작성자 정보를 어디에 둘지.
     *
     * 두 배치 모두 가로 밴드(`AuthorBand`)로 그리고 놓이는 위치만 다르다.
     *
     * - true  — 장소 목록 아래 맨 끝. 현재 배치.
     * - false — 히어로 바로 밑. 예전 배치.
     *
     * 팔로우 버튼의 "팔로잉" 상태 표시는 두 배치가 공유하므로 이 값과 무관하다.
     */
    const val AUTHOR_AT_BOTTOM = true

    /**
     * 장소 상세 시트의 배치.
     *
     * - true  — 지도가 시트를 꽉 채우고 정보가 그 위에 뜨는 현재 배치(`FullMapLayout`).
     *           코스 전체 보기·순번 핀 탭·이전/다음 이동이 여기 붙어 있다.
     * - false — 지도를 상단 히어로로만 두고 아래에 정보, 하단에 길찾기를 두는 예전 배치
     *           (`MapHeroLayout`). 코스 전체 보기·순번 핀·이전/다음이 없다.
     */
    const val PLACE_SHEET_FULL_MAP = true
}
