/** 번들 지도 코드에 대응하는 표시명. 요청 코드·원본 지명과 선택 상태는 바꾸지 않는다. */
@Composable
internal fun districtLabel(
    code: String,
    fallback: String,
): String {
    val resource = DISTRICT_LABELS[code] ?: return fallback
    return stringResource(resource)
}

/** Reverse-geocoded district names use the same labels as the home region filter. */
@Composable
internal fun districtNameLabel(original: String): String {
    val context = LocalContext.current
    val labels =
        remember(context) {
            val config = Configuration(context.resources.configuration).apply { setLocale(Locale.KOREAN) }
            val korean = context.createConfigurationContext(config).resources
            DISTRICT_LABELS.values.associateBy { korean.getString(it) }
        }
    val resource = labels[original] ?: return original
    return stringResource(resource)
}

